"""Nova MW Builder Plugin — a subagent that builds middleware plugins.

This is a *meta-plugin*: it generates other plugins. The ``mw-builder``
subagent knows the full Middleware.md contract and can scaffold a complete,
installable Nova middleware plugin from a natural-language description.

Provides:
  • subagent → mw-builder (knows the middleware API, generates plugins)
  • tool    → scaffold_middleware_plugin (writes plugin files to disk)
  • command → /mw-build (quick dispatch to the builder)
"""

